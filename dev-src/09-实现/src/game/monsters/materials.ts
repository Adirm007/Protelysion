export type MaterialVoice='读者'|'阳角少女'|'心爱的少女'|'怪人'|'黑幕';
export type MaterialEntry={name:string;voice:MaterialVoice;description:string};
/** 生命层级：Lv1–4=1 … Lv21–24=6，Lv25 及以上=7。 */
export function lifeTierOf(level:number):number{return Math.min(7,Math.max(1,Math.ceil(level/4)));}
/** 品质随等级；Boss 比同层小怪高一级；封顶神话（第6、7层级均为神话）。 */
export function levelQuality(level:number,boss=false):MaterialQuality{return MATERIAL_QUALITIES[Math.min(5,lifeTierOf(level)-1+(boss?1:0))]!;}
export function isMythicLevel(level:number):boolean{return levelQuality(level)==='神话';}
export function materialEffect(name:string,theme:string,region:string):string{return `于${theme}·${region}掉落的${name}，可用做素材`;}
export function materialFor(monsterId:string):MaterialEntry{
 const design=MONSTER_BY_ID[monsterId],entry=design&&MONSTER_MATERIALS[design.designId];
 if(!entry)throw new Error('怪物素材缺失：'+monsterId);
 return entry;
}
